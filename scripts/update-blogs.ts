先说好处。最直接的吸引力不用多说。不用早起赶早高峰的地铁，早上多睡半小时，穿着睡衣打开电脑就能开始干活。对于住在非一线城市的人来说，远程意味着你不必为了高薪工作举家搬迁。你可以在成都、重庆或者老家的小城市，拿着一线城市的工资。生活成本降下来，生活质量自然上去。

还有一些不太容易被量化但同样重要的好处。时间分配更灵活，接孩子放学、去医院看个病、家里有个急事——在办公室环境下这些都需要请假走流程，而远程工作下你只需要调整一下工作节奏就行。不少远程工作者提到，自从在家办公之后，陪伴家人的时间多了很多，这种幸福感是涨薪都换不来的。

